#!/bin/bash
#
# You may use:
# $DEBUG
# $FORCE
# $HEAD_COMMIT
# $OUTPUT_FILE
# $PREV_HEAD_COMMIT
# $LAST_PULL_COMMIT
# $SOURCE
# $SALT
#

target_dir=b8x
if [[ $SOURCE != "" ]]; then
    target_dir=b8x/$SOURCE
fi

dir=/var/www/$target_dir 
cd $dir

# >> NPM install
JS_DIR="run/bak/js"
npm_json_hash() {
    echo $(md5sum <(cat ./$JS_DIR/package-lock.json 2>&1) | cut -d' ' -f1)
}
npm_lock_hash() {
    echo $(md5sum <(cat ./$JS_DIR/package.json 2>&1) | cut -d' ' -f1)
}
npm_packages_hash() {
    echo $(md5sum <(ls -a ./$JS_DIR/node_modules 2>&1) | cut -d' ' -f1)
}

npm_json_pre_hash=$(npm_json_hash)
npm_lock_pre_hash=$(npm_lock_hash)
npm_packages_pre_hash=$(npm_packages_hash)

npm_installed=0

# $1 is the reason
npm_install() {
    local sentence='Installing npm packages. Reason:'

    if [ "$npm_installed" = '1' ]; then # avoid repeats
        return
    fi

    echo "$sentence $1"

    if [ -f ./$JS_DIR/package-lock.json ]; then
        cd ./$JS_DIR
        tmp=$(mktemp) # This will avoid concurrency problems
        npm ci --force --cache ./node_modules/.$tmp
        rm -R ./node_modules/.$tmp
        cd ../../../
    fi

    npm_installed=1
}
if [ "$FORCE" = '1' ]; then
    npm_install "by force"
fi
if ! [ -d ./$JS_DIR/node_modules ]; then
    npm_install 'the /node_modules directory does not exist'
fi
if [ "$npm_json_pre_hash" != "$LAST_PULL_NPM_JSON_POST_HASH" ]; then
    npm_install 'a change around the package.json file has been detected since the last remembered pull'
fi
if [ "$npm_lock_pre_hash" != "$LAST_PULL_NPM_LOCK_POST_HASH" ]; then
    npm_install 'a change around the package-lock.json file has been detected since the last remembered pull'
fi
if [ "$npm_packages_pre_hash" != "$LAST_PULL_NPM_PACKAGES_POST_HASH" ]; then
    npm_install 'a change around the /node_modules packages has been detected since the last remembered pull'
fi
if [ "$SALT" != "$LAST_PULL_SALT" ]; then
    npm_install 'the salt has changed'
fi

npm_json_post_hash=$(npm_json_hash)
npm_lock_post_hash=$(npm_lock_hash)
npm_packages_post_hash=$(npm_packages_hash)
# << NPM install

# >> Build
build_env_hash() {
    md5sum <(docker inspect $(cat /etc/hostname) | jq -r '.[0].Config.Env') | cut -d' ' -f1
}

build_env_pre_hash=$(build_env_hash)

built=0

# $1 is the reason
build() {
    local sentence='Building. Reason:'

    if [ "$built" = '1' ]; then # avoid repeats
        return
    fi

    echo "$sentence $1"

    /var/www/b8x/bin/build

    echo "Building dist with Vite..."
    if [ -f run/bak/js/vite.config.js ]; then
        npx vite build -c run/bak/js/vite.config.js
    else
        npx vite build
    fi
    
    echo "Copying static assets..."
    cp -R public/asset dist/ 2>/dev/null || true
    cp public/robots.txt dist/ 2>/dev/null || true

    echo "Cleaning old Vite assets..."
    # Gather currently active files (JS, CSS, and Assets) from the manifest generated by Vite
    ACTIVE_FILES=$(jq -r '.[].file, .[].css[]?, .[].assets[]?' ./dist/.vite/manifest.json 2>/dev/null | grep -v '^null$' | sort -u)
    if [ -n "$ACTIVE_FILES" ]; then
        # Find files older than 7 days and delete if they uniquely don't map to the manifest
        find ./dist/assets -type f -mtime +7 | while read -r file; do
            filename=$(basename "$file")
            if ! echo "$ACTIVE_FILES" | grep -q "$filename"; then
                rm -f "$file"
                echo "Deleted discarded asset: $file"
            fi
        done
    else
        echo "Vite manifest not found or parse error. Skipping GC."
    fi

    built=1
}
if [ "$FORCE" = '1' ]; then
    build "by force"
fi
if ! [ -d ./output ]; then
    build 'the /output directory does not exist'
fi
if ! [ -d ./dist ]; then
    build 'the /dist directory does not exist'
fi
if [ "$build_env_pre_hash" != "$LAST_PULL_BUILD_ENV_POST_HASH" ]; then
    build 'a change around envs has been detected since the last remembered pull'
fi
if [ "$HEAD_COMMIT" != "$PREV_HEAD_COMMIT" ]; then
    build 'the head commit has just been changed'
fi
if [ "$SALT" != "$LAST_PULL_SALT" ]; then
    build 'the salt has changed'
fi
if [ "$npm_installed" == '1' ]; then
    build 'npm packages have been (re)installed'
fi

build_env_post_hash=$(build_env_hash)
# << Build

# >> Service auto-update
service_updated=0

# $1 is the reason
update_service() {
    local sentence="Performing a rolling restart of the containers of the services (api, api-worker, api-proj...). Reason:"

    if [ "$service_updated" = '1' ]; then # avoid repeats
        return
    fi

    echo "$sentence $1"

    docker service update --force -d core_api >/dev/null
    docker service update --force -d core_api-worker >/dev/null
    docker service update --force -d core_api-proj >/dev/null

    for proj_service in $(docker service ls --format '{{.Name}}' | grep -E '_proj-'); do
        docker service update --force -d "$proj_service" >/dev/null
    done

    service_updated=1 
}
if [ "$FORCE" = '1' ]; then
    update_service "by force"
fi
if [ "$HEAD_COMMIT" != "$PREV_HEAD_COMMIT" ]; then
    update_service 'the head commit has just been changed'
fi
if [ "$built" == "1" ]; then
    update_service 'a new build has been made'
fi
if [ "$SALT" != "$LAST_PULL_SALT" ]; then
    update_service "the salt has changed"
fi
# << Service auto-update

cat <<ENVS > $OUTPUT_FILE
LAST_PULL_NPM_JSON_PRE_HASH="$npm_json_pre_hash"
LAST_PULL_NPM_LOCK_PRE_HASH="$npm_lock_pre_hash"
LAST_PULL_NPM_PACKAGES_PRE_HASH="$npm_packages_pre_hash"
LAST_PULL_NPM_JSON_POST_HASH="$npm_json_post_hash"
LAST_PULL_NPM_LOCK_POST_HASH="$npm_lock_post_hash"
LAST_PULL_NPM_PACKAGES_POST_HASH="$npm_packages_post_hash"
LAST_PULL_BUILD_ENV_PRE_HASH="$build_env_pre_hash"
LAST_PULL_BUILD_ENV_POST_HASH="$build_env_post_hash"
LAST_PULL_SALT="$SALT"
ENVS
